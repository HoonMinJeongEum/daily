DROP TEMPORARY TABLE IF EXISTS tmp_coupons;
CREATE TEMPORARY TABLE tmp_coupons (
  coupon_id BIGINT PRIMARY KEY
) ENGINE=Memory;

INSERT INTO tmp_coupons (coupon_id)
SELECT c.id
FROM coupon c
LEFT JOIN earned_coupon ec ON ec.coupon_id = c.id
WHERE c.purchased_at IS NULL
  AND ec.coupon_id IS NULL
LIMIT 100000;

INSERT INTO earned_coupon (coupon_id, member_id, used_at)
SELECT 
  t.coupon_id,
  (
    SELECT m.id
    FROM member m
    WHERE m.family_id = c.family_id
    ORDER BY RAND()          -- 간단히 랜덤 배정(아주 큰 데이터면 느릴 수 있음)
    LIMIT 1
  ) AS member_id,
  NULL
FROM tmp_coupons t
JOIN coupon c ON c.id = t.coupon_id;

UPDATE coupon c
JOIN tmp_coupons t ON t.coupon_id = c.id
SET c.purchased_at = NOW(6);

-- 무작위 30,000건 픽 → 사용 처리(used_at은 purchased_at~지금 사이 임의 시각)
WITH picked AS (
  SELECT e.id, c.purchased_at
  FROM earned_coupon e
  JOIN coupon c ON c.id = e.coupon_id
  WHERE e.used_at IS NULL
  ORDER BY RAND()
  LIMIT 30000
)
UPDATE earned_coupon e
JOIN picked p ON p.id = e.id
SET e.used_at = TIMESTAMPADD(
  SECOND,
  FLOOR(RAND() * GREATEST(1, TIMESTAMPDIFF(SECOND, p.purchased_at, NOW(6)))),
  p.purchased_at
);

