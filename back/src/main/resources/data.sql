INSERT INTO earned_sticker (created_at, member_id, sticker_id)
SELECT
  NOW() - INTERVAL (RAND() * 120) DAY,             -- 최근 4개월 내 랜덤 획득일
  m.id AS member_id,
  ((m.id + s.n) % 300) + 1 AS sticker_id           -- 1~300 순환
FROM member m
JOIN (
  SELECT 1 AS n UNION ALL SELECT 2 UNION ALL SELECT 3  -- 각 멤버당 3개
) s;

